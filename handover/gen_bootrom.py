#!/usr/bin/env python3
"""gen_bootrom.py - make the synthesizable boot ROM (rom1p1r) from sw/boot/rom.hex.

The RTL rom1p1r.sv has an EMPTY array: the testbenches load sw/boot/rom.hex into it by
back-door $readmemh. Synthesis would therefore build an all-zero ROM. This script writes
handover/rtl_synth/rom1p1r_bootrom.sv: same module name and ports, contents as a case
table, so the synthesis tool turns it into standard-cell logic (161 words, small).
Run again whenever sw/boot/rom.hex changes:   python handover/gen_bootrom.py
"""
import os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
hexf = os.path.join(root, "sw", "boot", "rom.hex")
out  = os.path.join(root, "handover", "rtl_synth", "rom1p1r_bootrom.sv")
words = [l.strip() for l in open(hexf) if l.strip() and not l.startswith("//")]
for w in words:
    int(w, 16)
    if len(w) != 8: sys.exit("rom.hex: expected 32-bit words, got " + w)
if len(words) > 1024: sys.exit("rom.hex larger than 4 KB ROM")
L = []
L.append("// rom1p1r_bootrom.sv - SYNTHESIS replacement for uncore_ip/src/generic/mem/rom1p1r.sv")
L.append("// GENERATED by handover/gen_bootrom.py from sw/boot/rom.hex (%d words). Do not edit." % len(words))
L.append("// Same module name, parameters and ports. Contents = boot ROM at 0x0000_1000 (word 0).")
L.append("// Read timing same as RTL: registered read, dout valid 1 cycle after addr (ce = 1).")
L.append("module rom1p1r #(parameter ADDR_WIDTH = 10, DATA_WIDTH = 32, PRELOAD_ENABLED = 0) (")
L.append("  input  logic                  clk,")
L.append("  input  logic                  ce,")
L.append("  input  logic [ADDR_WIDTH-1:0] addr,")
L.append("  output logic [DATA_WIDTH-1:0] dout")
L.append(");")
L.append("  logic [31:0] rom_q;")
L.append("  always_comb begin")
L.append("    case (addr)")
for i, w in enumerate(words):
    if int(w, 16) != 0:
        L.append("      %d'd%d: rom_q = 32'h%s;" % (10, i, w.lower()))
L.append("      default: rom_q = 32'h00000000;")
L.append("    endcase")
L.append("  end")
L.append("  always_ff @(posedge clk)")
L.append("    if (ce) dout <= rom_q[DATA_WIDTH-1:0];")
L.append("  // elaboration guard: this table is for the neumann 4 KB x 32 boot ROM only")
L.append("  if (ADDR_WIDTH != 10 || DATA_WIDTH != 32) begin : g_bad_param")
L.append("    $error(\"rom1p1r_bootrom: built for ADDR_WIDTH=10, DATA_WIDTH=32\");")
L.append("  end")
L.append("endmodule")
open(out, "w", newline="\n").write("\n".join(L) + "\n")
print("wrote", out, "-", len(words), "words,", sum(1 for w in words if int(w,16)), "non-zero")
