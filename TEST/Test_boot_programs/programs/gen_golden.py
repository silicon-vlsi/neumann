#!/usr/bin/env python3
"""gen_golden.py - make the input headers of the test programs and their golden results.

Writes programs/{gcd,sort,crc,mathx}_inputs.h and golden/<program>.golden (one hex word per
line). Golden values are computed here in Python, independently of the RISC-V code.
"""
import math, os, random, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
GOLD = os.path.join(HERE, '..', 'golden')
M32 = 0xFFFFFFFF
os.makedirs(GOLD, exist_ok=True)


def header(name, text):
    with open(os.path.join(HERE, name), 'w') as f:
        f.write('// generated by gen_golden.py - do not edit\n#include <stdint.h>\n' + text)


def golden(name, words):
    assert len(words) <= 64, name
    with open(os.path.join(GOLD, name + '.golden'), 'w') as f:
        for w in words:
            f.write('%08x\n' % (w & M32))


def s32(x):
    x &= M32
    return x - (1 << 32) if x >> 31 else x


rnd = random.Random(20261120)

# ---- gcd
pairs = [(0, 0), (0, 7), (7, 0), (1, 1), (48, 18), (1071, 462), (17, 13), (1024, 768),
         (0x80000000, 0x00100000), (0xFFFFFFFF, 0xFFFFFFFE), (0xFFFFFFFF, 0x00010001),
         (1836311903, 1134903170), (2147483647, 2147483646)]
for _ in range(19):
    g = rnd.choice([1, 2, 3, 6, 97, 1 << rnd.randrange(16), rnd.randrange(1, 1 << 16)])
    pairs.append((rnd.randrange(1, (1 << 32) // g) * g, rnd.randrange(1, (1 << 32) // g) * g))
header('gcd_inputs.h', '#define GCD_N %d\nuint32_t gcd_in[GCD_N][2] = {\n%s};\n' % (
    len(pairs), ''.join('  {0x%08xu, 0x%08xu},\n' % p for p in pairs)))
golden('gcd', [math.gcd(a, b) for a, b in pairs])

# ---- sort (48 values incl. duplicates, 0, max, sign-bit values)
vals = [0, M32, 0x80000000, 0x7FFFFFFF, 1, 1, 0xDEADBEEF, 0x12345678]
vals += [rnd.getrandbits(32) for _ in range(40)]
rnd.shuffle(vals)
header('sort_inputs.h', '#define SORT_N %d\nuint32_t sort_in[SORT_N] = {\n%s};\n' % (
    len(vals), ''.join('  0x%08xu,\n' % v for v in vals)))
su = sorted(vals)
ss = sorted(vals, key=s32)
golden('sort', su + ss[:4] + ss[-4:])

# ---- crc32
CRC_N = 256
buf = bytes(rnd.getrandbits(8) for _ in range(CRC_N))
header('crc_inputs.h', '#define CRC_N %d\nuint8_t crc_in[CRC_N] __attribute__((aligned(4))) = {\n%s};\n' % (
    CRC_N, ''.join('  ' + ', '.join('0x%02x' % b for b in buf[i:i + 16]) + ',\n' for i in range(0, CRC_N, 16))))
sum8s = sum(b - 256 if b > 127 else b for b in buf)
h = [buf[i] | buf[i + 1] << 8 for i in range(0, CRC_N, 2)]
sum16 = sum(h)
sum16s = sum(x - 65536 if x > 32767 else x for x in h)
rev = bytes(reversed(buf))
x = bytearray(rev)
for i in range(CRC_N // 2):
    v = (buf[2 * i] | buf[2 * i + 1] << 8) ^ 0xA5A5
    x[2 * i], x[2 * i + 1] = v & 0xFF, v >> 8
golden('crc32', [zlib.crc32(b'123456789'), zlib.crc32(buf), zlib.crc32(buf[3:104]),
                 sum8s, sum16, sum16s, zlib.crc32(rev), zlib.crc32(bytes(x))])

# ---- sieve
N = 2048
pr = [p for p in range(2, N) if all(p % d for d in range(2, int(p ** 0.5) + 1))]
golden('sieve', [len(pr), sum(pr), pr[-1]] + pr[:8] + pr[-4:])

# ---- mathx
mul = [(0, 5), (1, 0xFFFFFFFF), (3, 7), (0xFFFF, 0xFFFF), (0x12345678, 0x9ABCDEF0)]
mul += [(rnd.getrandbits(32), rnd.getrandbits(32)) for _ in range(3)]
div = [(100, 7), (0xFFFFFFFF, 1), (0xFFFFFFFF, 0xFFFFFFFF), (5, 9), (0x80000000, 3)]
div += [(rnd.getrandbits(32), rnd.randrange(1, 1 << rnd.randrange(1, 32))) for _ in range(3)]
header('mathx_inputs.h', 'uint32_t mul_in[8][2] = {\n%s};\nuint32_t div_in[8][2] = {\n%s};\n' % (
    ''.join('  {0x%08xu, 0x%08xu},\n' % p for p in mul), ''.join('  {0x%08xu, 0x%08xu},\n' % p for p in div)))
f0, f1 = 0, 1
for _ in range(46):
    f0, f1 = f1, f0 + f1
p64 = mul[7][0] * mul[7][1]
w = [a * b for a, b in mul]
for a, b in div:
    w += [a // b, a % b]
golden('mathx', w + [f1, p64 >> 32, p64])

# ---- rtos (fixed expected values, see programs/rtos/rtos_test.c)
golden('rtos', [210, 20, 1, 10, 1, 40, 1, 0x5A5A, 1])
print('inputs + golden written: gcd sort crc32 sieve mathx rtos')
