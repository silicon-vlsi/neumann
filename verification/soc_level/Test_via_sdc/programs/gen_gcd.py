#!/usr/bin/env python3
# gen_gcd.py - make the gcd test inputs and the golden results.
#   programs/gcd_inputs.h : input pairs (C array, placed in .data -> DRAM)
#   golden/gcd.golden     : expected gcd per pair, one 32-bit hex word per line
# Golden values come from Python math.gcd (independent of the RISC-V code).
import math, os, random
here = os.path.dirname(os.path.abspath(__file__))
fixed = [
    (0, 0), (0, 7), (7, 0), (1, 1), (48, 18), (18, 48), (1071, 462),
    (270, 192), (17, 13), (1024, 768), (0x80000000, 0x00100000),
    (0xFFFFFFFF, 0xFFFFFFFE), (0xFFFFFFFF, 0xFFFFFFFF), (0xFFFFFFFF, 0x00010001),
    (1836311903, 1134903170),          # consecutive Fibonacci: worst case for Euclid
    (2147483647, 2147483646),          # 2^31-1 is prime
    (3 * 5 * 7 * 11 * 13 * 17, 5 * 11 * 17 * 19 * 23),
    (123456789 * 3, 987654321 * 3 % (1 << 32)),
]
rnd = random.Random(2026)
for _ in range(14):
    g = rnd.choice([1, 2, 3, 6, 12, 97, 1 << rnd.randrange(16), rnd.randrange(1, 1 << 16)])
    a = (rnd.randrange(1, (1 << 32) // g)) * g
    b = (rnd.randrange(1, (1 << 32) // g)) * g
    fixed.append((a, b))
pairs = fixed
with open(os.path.join(here, 'gcd_inputs.h'), 'w') as f:
    f.write('// generated by gen_gcd.py - do not edit\n')
    f.write('#define GCD_N %d\n' % len(pairs))
    f.write('uint32_t gcd_in[GCD_N][2] = {\n')
    for a, b in pairs:
        f.write('  {0x%08xu, 0x%08xu},\n' % (a, b))
    f.write('};\n')
os.makedirs(os.path.join(here, '..', 'golden'), exist_ok=True)
with open(os.path.join(here, '..', 'golden', 'gcd.golden'), 'w') as f:
    for a, b in pairs:
        f.write('%08x\n' % math.gcd(a, b))
print('gcd: %d pairs' % len(pairs))
